// build-icons.mjs — turn vendored Tabler SVGs into the diagram icon table.
//
//   npm --workspace @content-os/engine-production run icons
//
// Icons come from Tabler Icons (MIT, https://tabler.io/icons). The specific
// files this system uses are vendored in src/diagrams/icons/tabler/ (each with
// the upstream LICENSE). This script reads those files, extracts every
// <path d="..."/> and writes src/diagrams/icons.generated.mjs — a plain JS
// object the runtime reads with no fs, no network and no dependency.
//
// Re-run only when the ICON_MAP changes or a vendored SVG is updated. The
// generated file is committed (same precedent as assets/catalog.json) and is
// never edited by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, '..');
const SVG_DIR = path.join(PKG_ROOT, 'src', 'diagrams', 'icons', 'tabler');
const OUT = path.join(PKG_ROOT, 'src', 'diagrams', 'icons.generated.mjs');

// Our public icon key -> the vendored Tabler file name. The key is the stable
// id diagrams use; the file is upstream's name. Keep keys stable.
const ICON_MAP = {
  user: 'user',
  doc: 'file-text',
  code: 'code',
  gear: 'settings',
  database: 'database',
  send: 'send',
  check: 'check',
  bolt: 'bolt',
  chat: 'message',
  chart: 'chart-bar',
};

function readPaths(fileName) {
  const file = path.join(SVG_DIR, `${fileName}.svg`);
  if (!fs.existsSync(file)) throw new Error(`vendored icon not found: ${file}`);
  const svg = fs.readFileSync(file, 'utf8');
  const paths = [];
  const re = /<path\b[^>]*?\bd="([^"]+)"[^>]*?\/?>/g;
  let m;
  while ((m = re.exec(svg)) !== null) paths.push(m[1]);
  if (!paths.length) throw new Error(`no <path> found in ${file}`);
  return paths;
}

const entries = Object.entries(ICON_MAP).map(([key, file]) => {
  const paths = readPaths(file);
  return [key, file, paths];
});

const body = entries
  .map(([key, file, paths]) => {
    const list = paths.map((d) => `    ${JSON.stringify(d)},`).join('\n');
    return `  // ${key} <- tabler ${file}.svg\n  ${JSON.stringify(key)}: [\n${list}\n  ],`;
  })
  .join('\n');

const out = `// icons.generated.mjs — GENERATED by tools/build-icons.mjs. DO NOT EDIT.
//
// Icon geometry is sourced from Tabler Icons (MIT) — https://tabler.io/icons.
// Each entry is a list of SVG path "d" strings on a 24x24 grid. The wrapper
// attributes (viewBox, fill=none, stroke=currentColor, stroke-width=2, round
// caps/joins) are emitted by primitives.iconGroup(), so only the paths live
// here. Vendored sources + LICENSE: src/diagrams/icons/tabler/.
//
// Regenerate: npm --workspace @content-os/engine-production run icons
export const COMPUTED_ICON_PATHS = {
${body}
};
`;

fs.writeFileSync(OUT, out, 'utf8');
console.log(`icons written: ${OUT}\n  ${entries.map(([k, f, p]) => `${k}(${p.length})`).join(' ')}`);
